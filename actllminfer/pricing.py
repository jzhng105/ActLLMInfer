"""List prices for the models ActLLMInfer can call, and for reference providers.

The table (``actllminfer/data/model_prices.json``) holds each provider's
official per-token price, read at the provider's own route rather than a
reseller's, and is regenerated by ``scripts/update_prices.py``. It is the
price source for ActLLMInfer's callers, ActRouter included.

Examples::

    from actllminfer.pricing import get_price, estimate_cost

    get_price("anthropic/claude-sonnet-4-6").output_per_mtok   # 15.0
    get_price("glm-4.6")             # provider inferred from the model name
    get_price("kimi:kimi-k2.5")      # same separators as completion()
    estimate_cost("openai/gpt-5-mini", prompt_tokens=1200, completion_tokens=300)

Long-context pricing is all-or-nothing per request, as providers bill it:
once the prompt crosses a tier's threshold (e.g. 200k tokens on Gemini 2.5
Pro), every token in the request is billed at that tier's rates.
:func:`estimate_cost` applies this; :meth:`ModelPrice.rates_for` exposes it.

Models served through NVIDIA NIM or Hugging Face have no entry: neither
publishes per-token list prices, so :func:`get_price` returns ``None``.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any, Optional

from .factory import _infer_provider

_DATA = Path(__file__).with_name("data") / "model_prices.json"

#: ActLLMInfer's provider aliases -> the table's provider names
_ALIASES = {
    "kimi": "moonshot",
    "zhipu": "zhipuai",
    "glm": "zhipuai",
    "zai": "zhipuai",
    "claude": "anthropic",
    "gemini": "google",
    "dashscope": "alibaba",
    "qwen": "alibaba",
}


@dataclass(frozen=True)
class ContextTier:
    """Rates for requests whose prompt exceeds `above_tokens`."""

    above_tokens: int
    input_per_mtok: float
    output_per_mtok: float
    cache_read_per_mtok: Optional[float] = None


@dataclass(frozen=True)
class ModelPrice:
    provider: str
    model: str
    input_per_mtok: float
    output_per_mtok: float
    cache_read_per_mtok: Optional[float] = None
    context_window: Optional[int] = None
    max_output_tokens: Optional[int] = None
    supports_tools: bool = False
    supports_vision: bool = False
    supports_reasoning: bool = False
    deprecation_date: Optional[str] = None
    #: long-context tiers, ascending by threshold
    context_tiers: tuple[ContextTier, ...] = ()
    #: the provider bills a tier once the prompt *reaches* its threshold
    #: (xAI) rather than exceeds it
    threshold_inclusive: bool = False
    #: name of the ActLLMInfer chat class for this provider, or None when the
    #: price is a reference price for a provider ActLLMInfer cannot call
    client: Optional[str] = None

    def rates_for(self, prompt_tokens: int) -> tuple[float, float, Optional[float]]:
        """(input, output, cache-read) USD per Mtok for a request whose prompt
        is `prompt_tokens` long, cached tokens included."""
        rates = (self.input_per_mtok, self.output_per_mtok, self.cache_read_per_mtok)
        for tier in self.context_tiers:
            crossed = prompt_tokens > tier.above_tokens or (
                self.threshold_inclusive and prompt_tokens == tier.above_tokens
            )
            if crossed:
                rates = (tier.input_per_mtok, tier.output_per_mtok, tier.cache_read_per_mtok)
        return rates


@dataclass(frozen=True)
class PriceTable:
    as_of: str
    source: str
    models: tuple[ModelPrice, ...]

    def get(self, provider: str, model: str) -> Optional[ModelPrice]:
        return _index(self).get((provider, model.lower()))

    def for_provider(self, provider: str) -> list[ModelPrice]:
        provider = _ALIASES.get(provider.lower(), provider.lower())
        return [m for m in self.models if m.provider == provider]

    def providers(self) -> list[str]:
        return sorted({m.provider for m in self.models})


@lru_cache(maxsize=8)
def _index(table: PriceTable) -> dict[tuple[str, str], ModelPrice]:
    return {(m.provider, m.model.lower()): m for m in table.models}


def _parse(payload: dict[str, Any]) -> PriceTable:
    providers = payload.get("providers", {})
    fields = set(ModelPrice.__dataclass_fields__) - {"client", "context_tiers", "threshold_inclusive"}
    models = tuple(
        ModelPrice(
            **{k: v for k, v in m.items() if k in fields},
            context_tiers=tuple(
                ContextTier(**t) for t in sorted(m.get("context_tiers") or (), key=lambda t: t["above_tokens"])
            ),
            threshold_inclusive=bool(providers.get(m["provider"], {}).get("threshold_inclusive")),
            client=providers.get(m["provider"], {}).get("client"),
        )
        for m in payload.get("models", [])
    )
    return PriceTable(as_of=str(payload.get("as_of", "")), source=str(payload.get("source", "")), models=models)


@lru_cache(maxsize=1)
def load_prices(path: Optional[str] = None) -> PriceTable:
    """The bundled table, or the one at `path`."""
    return _parse(json.loads(Path(path or _DATA).read_text(encoding="utf-8")))


def _split(spec: str, provider: Optional[str], table: PriceTable) -> tuple[Optional[str], str]:
    if provider is None:
        for sep in (":", "/"):
            head, _, tail = spec.partition(sep)
            if tail and _ALIASES.get(head.lower(), head.lower()) in table.providers():
                return _ALIASES.get(head.lower(), head.lower()), tail
        provider = _infer_provider(spec)
    if provider is None:
        return None, spec
    return _ALIASES.get(provider.lower(), provider.lower()), spec


def get_price(
    model: str, provider: Optional[str] = None, table: Optional[PriceTable] = None
) -> Optional[ModelPrice]:
    """The list price for `model`, or None if the table has no entry.

    `model` may carry a provider (``"openai/gpt-5.5"``, ``"kimi:kimi-k2.5"``);
    otherwise `provider` is used, or inferred from the model name the same
    way :func:`actllminfer.init_chat_model` does. Model ids match
    case-insensitively (``minimax-m2.5`` finds ``MiniMax-M2.5``).
    """
    table = table or load_prices()
    name, spec = _split(model, provider, table)
    if name is not None:
        return table.get(name, spec)
    matches = [m for m in table.models if m.model.lower() == spec.lower()]
    return matches[0] if len(matches) == 1 else None


def estimate_cost(
    model: str,
    prompt_tokens: int,
    completion_tokens: int,
    provider: Optional[str] = None,
    cached_prompt_tokens: int = 0,
) -> Optional[float]:
    """USD for a call at list price, or None if the model has no price.

    `prompt_tokens` includes `cached_prompt_tokens`; together they decide the
    long-context tier, whose rates then apply to every token of the call.
    """
    price = get_price(model, provider)
    if price is None:
        return None
    input_rate, output_rate, cache_rate = price.rates_for(prompt_tokens)
    cached = min(cached_prompt_tokens, prompt_tokens)
    if cache_rate is None:
        cache_rate = input_rate
    return (
        (prompt_tokens - cached) * input_rate
        + cached * cache_rate
        + completion_tokens * output_rate
    ) / 1_000_000


__all__ = ["ContextTier", "ModelPrice", "PriceTable", "estimate_cost", "get_price", "load_prices"]
